package org.yc.learn.res;

import dev.langchain4j.community.model.dashscope.QwenStreamingChatModel;
import dev.langchain4j.model.LambdaStreamingResponseHandler;
import dev.langchain4j.model.chat.response.ChatResponse;
import dev.langchain4j.model.chat.response.CompleteToolCall;
import dev.langchain4j.model.chat.response.PartialThinking;
import dev.langchain4j.model.chat.response.PartialToolCall;
import dev.langchain4j.model.chat.response.StreamingChatResponseHandler;
import org.yc.learn.AppConfig;

import static dev.langchain4j.model.LambdaStreamingResponseHandler.onPartialResponse;

/**
 * @author zhengyanchuang
 * @version 1.0
 * @description TODO
 * @date 2026/11/3 16:31
 */
public class DemoStreamingChatResponseHandler {

    public static void main(String[] args) {


        QwenStreamingChatModel model = QwenStreamingChatModel.builder()
                .apiKey(AppConfig.apiKey())
                .modelName(AppConfig.modelName())
                .isMultimodalModel(true).build();

        String userMessage = "给我讲个笑话";


        model.chat("说一段绕口令", onPartialResponse(System.out::print));

        model.chat(userMessage, new StreamingChatResponseHandler() {

            /**
             * Called when the model starts generating a partial response.
             * 当生成下一个部分文本响应时：调用 onPartialResponse(String)。
             * @param partialResponse the partial response generated by the model
             */
            @Override
            public void onPartialResponse(String partialResponse) {
                System.out.println("当生成下一个部分文本响应时 onPartialResponse: " + partialResponse);
            }

            /**
             * Called when the model starts generating a partial thinking.
             * 当生成下一个部分思考时：调用 onPartialThinking(PartialThinking)。
             * @param partialThinking the partial thinking generated by the model
             */
            @Override
            public void onPartialThinking(PartialThinking partialThinking) {
                System.out.println("当生成下一个部分思考时 onPartialThinking: " + partialThinking);
            }

            /**
             * Called when the model starts generating a partial tool call.
             * 当生成下一个部分工具调用时：调用 onPartialToolCall(PartialToolCall)。
             * @param partialToolCall the partial tool call generated by the model
             */
            @Override
            public void onPartialToolCall(PartialToolCall partialToolCall) {
                System.out.println("当生成下一个部分工具调用时 onPartialToolCall: " + partialToolCall);
            }

            /**
             * Called when the model starts generating a complete tool call.
             * 当生成完整工具调用时：调用 onCompleteToolCall(CompleteToolCall)。
             * @param completeToolCall the complete tool call generated by the model
             */
            @Override
            public void onCompleteToolCall(CompleteToolCall completeToolCall) {
                System.out.println("当生成完整工具调用时 onCompleteToolCall: " + completeToolCall);
            }

            /**
             * Called when the model starts generating a complete response.
             * 当生成完整响应时：调用 onCompleteResponse(ChatResponse)。
             * @param completeResponse the complete response generated by the model
             */
            @Override
            public void onCompleteResponse(ChatResponse completeResponse) {
                System.out.println("当生成完整响应时 onCompleteResponse: " + completeResponse);
            }

            /**
             * Called when an error occurs during response generation.
             * 当响应生成过程中发生错误时：调用 onError(Throwable)。
             * @param error the error that occurred
             */
            @Override
            public void onError(Throwable error) {
                error.printStackTrace();
            }
        });

    }
}
